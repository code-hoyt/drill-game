export const FONT_KEY = 'pixel';

export function createPixelFont(scene) {
  const chars = Object.keys(G).join('');
  const cw = 4, ch = 6, perRow = 16;
  const rows = Math.ceil(chars.length / perRow);
  const tex = scene.textures.createCanvas('pixelfont_img', cw * perRow, ch * rows);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  [...chars].forEach((c, i) => {
    const ox = (i % perRow) * cw, oy = Math.floor(i / perRow) * ch;
    G[c].forEach((row, y) => [...row].forEach((p, x) => { if (p === '#') ctx.fillRect(ox + x, oy + y, 1, 1); }));
  });
  tex.refresh();
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: 'pixelfont_img', width: cw, height: ch, chars, charsPerRow: perRow,
    spacing: { x: 0, y: 0 }, offset: { x: 0, y: 0 }, lineSpacing: 1,
  });
  data.data.size = ch; // so a bitmapText size of 6 = 1x, 12 = 2x ...
  scene.cache.bitmapFont.add(FONT_KEY, data);
}
